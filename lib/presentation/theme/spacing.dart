abstract final class Spacing {
  /// The spacing value for no spacing.
  ///
  /// * `space` = 0.
  static const double none = 0;

  /// The spacing value for a single unit of spacing.
  ///
  /// * `space` = 1.
  static const double dot = 1;

  /// The spacing value for extra extra extra small spacing.
  ///
  /// * `space` = 2.
  static const double xs3 = 2;

  /// The spacing value for extra small spacing.
  ///
  /// * `space` = 4.
  static const double xs2 = 4;

  /// The spacing value for extra small spacing.
  ///
  /// * `space` = 6.
  static const double xs = 6;

  /// The spacing value for small spacing.
  ///
  /// * `space` = 8.
  static const double sm = 8;

  /// The spacing value for medium spacing.
  ///
  /// * `space` = 12.
  static const double md = 12;

  /// The spacing value for large spacing.
  ///
  /// * `space` = 16.
  static const double lg = 16;

  /// The spacing value for extra large spacing.
  ///
  /// * `space` = 24.
  static const double xl = 24;
}
